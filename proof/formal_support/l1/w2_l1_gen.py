"""Generate all L1 Lean data modules from the reduced certificate (hash-checked, read-only).

Untrusted generator: everything it writes is re-checked by the Lean kernel (`decide +kernel`) through
checkers whose soundness is proved in Lean (ClaudeL1.KC.*).  A wrong export makes a check fail; it
cannot make a false theorem.

Writes (under claude/formal/l1/lean/ClaudeL1/Data/):
  Mult.lean            multiplier table gtree (10^4 * domainWeight(5593/10000, .)[code])
  Kernel.lean          kernel factor columns (delta = 10^60 scaled), collected total PK,
                       theorem ktotal_ok : ktotal.check = true   (Kronecker zero test)
  SOS/T00..Tnn.lean    running totals of the SOS chain (T00 = 0)
  SOS/C01..Cnn.lean    SOS chunks: columns + theorem chunkNN_ok (decide +kernel)
  SOS/Glue.lean        allTerms and the telescoped identity sos_total
  Assembly.lean        minorant numerators, final residual l1 check asm_ok (balanced digits)
and l1/data/manifest.json (build order, per-module statistics, all exact constants).

usage:  python w2_l1_gen.py [--max-leaves 13000] [--only kernel,mult,sos,asm]
"""
import argparse
import hashlib
import json
import sys
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import w2_l1_model as M  # noqa: E402

OUT = HERE / "lean" / "ClaudeL1" / "Data"
NS = "ThomsonN9.Claude.L1.Data"


# ------------------------------------------------------------------ Lean emission helpers
def lit(c):
    c = int(c)
    return f"(Int.ofNat {c})" if c >= 0 else f"(Int.negSucc {-c - 1})"


def sorted_items(d):
    return sorted(((tuple(int(x) for x in e), int(c)) for e, c in d.items() if int(c) != 0),
                  key=lambda ec: M.kexp(ec[0]))


def tree(items):
    if not items:
        return "L (Int.ofNat 0) 0 0 0"
    if len(items) == 1:
        (a, b, d), c = items[0]
        return f"L {lit(c)} {a} {b} {d}"
    m = len(items) // 2
    return f"N ({tree(items[:m])})\n ({tree(items[m:])})"


def poly_dict(p):
    """flint fmpz_mpoly -> {exp: int}"""
    return {tuple(int(x) for x in e): int(c) for e, c in zip(p.monoms(), p.coeffs())}


def l1d(d):
    return sum(abs(c) for c in d.values())


def maxdeg(d):
    return max((max(e) for e in d), default=0)


HEADER = "-- GENERATED by claude/formal/l1/w2_l1_gen.py from near-sharp-d10-reduced-D60.json\n" \
         f"-- (SHA-256 {M.SHA}).  Do not edit.\n"


GENERATED = {}


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    path.write_bytes(data)
    GENERATED[path.relative_to(HERE).as_posix()] = hashlib.sha256(data).hexdigest()
    return len(data)


# ------------------------------------------------------------------ modules
def gen_mult():
    lines = [HEADER, "import ClaudeL1.KC.Chain", "", f"namespace {NS}", "open ThomsonN9.Claude.L1.KC", "",
             "/-- multiplier table: `gtree c = 10^4 * domainWeight (5593/10000) u v t c` for `c < 6`",
             "(proved in `ClaudeL1.Bridge`), `0` otherwise -/",
             "def gtree : Nat → PTree"]
    for code in range(6):
        d = poly_dict(M.gpoly(code))
        lines.append(f"  | {code} => {tree(sorted_items(d))}".replace("\n", "\n    "))
    lines.append("  | _ => L (Int.ofNat 0) 0 0 0")
    lines += ["", f"end {NS}", ""]
    return write(OUT / "Mult.lean", "\n".join(lines))


def gen_kernel(kcols, pk):
    pkd = poly_dict(pk)
    l1k = sum(M.expr_l1(cols, k) for k, cols in enumerate(kcols))
    l1b = l1k + l1d(pkd)
    w = l1b.bit_length() + 1
    assert l1b < 2 ** w and maxdeg(pkd) < 21
    blocks = "[" + ",\n ".join(
        "[" + ", ".join("[" + ", ".join(lit(x) for x in c) + "]" for c in cols) + "]" for cols in kcols) + "]"
    lines = [HEADER, "import ClaudeL1.KC.Kernel", "import ClaudeL1.KC.Chain", "",
             f"namespace {NS}", "open ThomsonN9.Claude.L1.KC", "",
             "/-- kernel factor columns, block k = 0..9 (block 10 of the certificate is identically zero and",
             "dropped): `kblocks[k][r][i] = 10^60 * B_k[i][r]` -/",
             f"noncomputable def kblocks : List (List (List Int)) :=\n {blocks}", "",
             f"/-- the collected kernel total `Σ_k exprPoly (kblocks[k]) k` ({len(pkd)} terms) -/",
             f"noncomputable def PK : PTree :=\n {tree(sorted_items(pkd))}", "",
             f"noncomputable def ktotal : KTotal := {{ w := {w}, blocks := kblocks, total := PK }}", "",
             "theorem ktotal_ok : ktotal.check = true := by decide +kernel", "",
             "theorem kernel_identity {α : Type u} [Lean.Grind.CommRing α] (x y z : α) :",
             "    (kernelPoly kblocks).eval x y z = PK.toPoly.eval x y z :=",
             "  KTotal.check_sound ktotal ktotal_ok x y z", "",
             f"end {NS}", ""]
    size = write(OUT / "Kernel.lean", "\n".join(lines))
    return {"module": "ClaudeL1.Data.Kernel", "w": w, "pk_terms": len(pkd), "bytes": size,
            "l1_bound_bits": l1b.bit_length()}


def plan_chunks(blocks, max_leaves):
    """group columns by multiplier code (blocks 2r, 2r+1 share code r); split greedily, evenly"""
    bycode = {}
    for code, cols in blocks:
        bycode.setdefault(code, []).extend(cols)
    chunks = []
    for code in sorted(bycode):
        cols = bycode[code]
        total = sum(len(c) for c in cols)
        n = max(1, -(-total // max_leaves))
        target = total / n
        cur, acc = [], 0
        for c in cols:
            if cur and acc + len(c) > target * 1.02 and len([x for x in chunks if x[0] == code]) < n - 1:
                chunks.append((code, cur))
                cur, acc = [], 0
            cur.append(c)
            acc += len(c)
        if cur:
            chunks.append((code, cur))
    return chunks


def gen_sos(blocks, max_leaves):
    chunks = plan_chunks(blocks, max_leaves)
    n = len(chunks)
    stats = []
    write(OUT / "SOS" / "T00.lean", "\n".join([
        HEADER, "import ClaudeL1.KC.Chain", "", f"namespace {NS}.SOS", "open ThomsonN9.Claude.L1.KC", "",
        "noncomputable def T00 : PTree := zeroTree", "", f"end {NS}.SOS", ""]))
    run = M.ZERO
    prevd = {(0, 0, 0): 0}
    for i, (code, cols) in enumerate(chunks, start=1):
        g = M.gpoly(code)
        gd = poly_dict(g)
        acc = M.ZERO
        for c in cols:
            cp = M.CTX.from_dict(c)
            acc += cp * cp
        run = run + g * acc
        nextd = poly_dict(run)
        l1b = l1d(gd) * sum(l1d(c) ** 2 for c in cols) + max(l1d(prevd), 0) + l1d(nextd)
        w = l1b.bit_length() + 1
        assert maxdeg(gd) + 2 * max(maxdeg(c) for c in cols) < 21 and maxdeg(nextd) < 21
        tname, pname = f"T{i:02d}", f"T{i - 1:02d}"
        tsize = write(OUT / "SOS" / f"{tname}.lean", "\n".join([
            HEADER, "import ClaudeL1.KC.Chain", "", f"namespace {NS}.SOS", "open ThomsonN9.Claude.L1.KC", "",
            f"/-- running SOS total after chunk {i} ({len(nextd)} terms) -/",
            f"noncomputable def {tname} : PTree :=\n {tree(sorted_items(nextd))}", "", f"end {NS}.SOS", ""]))
        cn = f"C{i:02d}"
        lines = [HEADER, "import ClaudeL1.KC.Chain", "import ClaudeL1.Data.Mult",
                 f"import ClaudeL1.Data.SOS.{pname}", f"import ClaudeL1.Data.SOS.{tname}", "",
                 f"namespace {NS}.SOS", "open ThomsonN9.Claude.L1.KC", "",
                 f"-- chunk {i}: multiplier code {code}, {len(cols)} columns, "
                 f"{sum(len(c) for c in cols)} column leaves, w = {w}"]
        for j, c in enumerate(cols):
            lines.append(f"noncomputable def c{i:02d}_{j} : PTree :=\n {tree(sorted_items(c))}")
        lines.append(f"noncomputable def cols{i:02d} : List PTree :=\n  [" +
                     ", ".join(f"c{i:02d}_{j}" for j in range(len(cols))) + "]")
        lines += ["",
                  f"theorem chunk{i:02d}_ok : (SOSChunk.ofCode gtree {w} {code} cols{i:02d} {pname} {tname}).check = true := by",
                  "  decide +kernel", "", f"end {NS}.SOS", ""]
        csize = write(OUT / "SOS" / f"{cn}.lean", "\n".join(lines))
        stats.append({"module": f"ClaudeL1.Data.SOS.{cn}", "code": code, "cols": len(cols),
                      "col_leaves": sum(len(c) for c in cols), "total_terms": len(nextd), "w": w,
                      "bytes": csize, "t_bytes": tsize})
        prevd = nextd
    # glue
    imports = [f"import ClaudeL1.Data.SOS.C{i:02d}" for i in range(1, n + 1)]
    terms = " ++\n  (".join(f"termsOf {code} cols{i:02d}" for i, (code, _) in enumerate(chunks, start=1))
    terms = "(" * 0 + terms + ")" * (n - 1)
    hs = "\n".join(f"  have h{i:02d} := chunk_step gtree _ _ _ _ _ chunk{i:02d}_ok x y z" for i in range(1, n + 1))
    rws = ", ".join(f"h{i:02d}" for i in range(n, 0, -1))
    lines = [HEADER, "import ClaudeL1.KC.Chain", *imports, "", f"namespace {NS}.SOS",
             "open ThomsonN9.Claude.L1.KC", "",
             "/-- all SOS terms (multiplier code, column), in chain order -/",
             f"noncomputable def allTerms : List (Nat × PTree) :=\n  {terms}", "",
             "/-- the final running total is the sum of all SOS terms, on every commutative ring -/",
             "theorem sos_total {α : Type u} [Lean.Grind.CommRing α] (x y z : α) :",
             f"    T{n:02d}.toPoly.eval x y z = sumVal gtree x y z allTerms := by",
             hs,
             "  have h00 : T00.toPoly.eval x y z = 0 := eval_zeroTree x y z",
             f"  rw [{rws}, h00]",
             "  simp only [allTerms, sumVal_append]",
             "  grind", "",
             f"end {NS}.SOS", ""]
    write(OUT / "SOS" / "Glue.lean", "\n".join(lines))
    return chunks, run, stats


def gen_assembly(H, c0, pk, tot, Lres):
    pkd, td = poly_dict(pk), poly_dict(tot)
    l1b = abs(M.HSCALE) * 3 * sum(abs(h) for h in H) + abs(c0) + M.KSCALE * l1d(pkd) + M.SSCALE * 3 * l1d(td)
    w = l1b.bit_length() + 2
    assert l1b < 2 ** (w - 1)
    n = None
    lines = [HEADER, "import ClaudeL1.KC.Assembly", "import ClaudeL1.Data.Kernel", "import ClaudeL1.Data.SOS.Last", "",
             f"namespace {NS}", "open ThomsonN9.Claude.L1.KC", "",
             "/-- minorant numerators: `h_new(t) = Σ_i hNum[i] t^i / 10^60` -/",
             "noncomputable def hNum : List Int :=\n  [" + ", ".join(lit(h) for h in H) + "]", "",
             f"/-- `-S e/36` with `S = 9*10^124`, `e` = raw_energy -/",
             f"noncomputable def c0 : Int := {lit(c0)}", "",
             "noncomputable def asm : Assembly :=",
             f"  {{ w := {w}, hs := hNum, hscale := {lit(M.HSCALE)}, c0 := c0, kscale := {lit(M.KSCALE)},",
             f"    K := PK, sscale := {lit(M.SSCALE)}, T := SOS.Tlast }}", "",
             "/-- `S * L_new` with `L_new` = (raw_energy - certified_energy)/36 -/",
             f"def Lres : Nat := {Lres}", "",
             "theorem asm_ok : asm.checkL1 Lres = true := by decide +kernel", "",
             "theorem asm_sound : boxL1 21 asm.residual ≤ Lres ∧ asm.residual.DegLt 21 :=",
             "  Assembly.checkL1_sound asm Lres asm_ok", "",
             f"end {NS}", ""]
    size = write(OUT / "Assembly.lean", "\n".join(lines))
    return {"module": "ClaudeL1.Data.Assembly", "w": w, "bytes": size, "l1_bound_bits": l1b.bit_length()}


def qlit(s):
    """exact JSON rational string -> Lean ℚ term"""
    f = F(s)
    p, q = f.numerator, f.denominator
    num = f"({p} : ℚ)" if p >= 0 else f"(-{-p} : ℚ)"
    return num if q == 1 else f"({num} / {q})"


def gen_numbers(data, H):
    hs = data["minorant"]
    assert [F(x) for x in hs] == [F(h, M.DELTA) for h in H]
    vec = ",\n    ".join(qlit(x) for x in hs)
    hv = ",\n    ".join(str(h) for h in H)
    lines = [HEADER,
             "import Mathlib.Data.Real.Basic",
             "import Mathlib.Algebra.BigOperators.Fin",
             "import Mathlib.Tactic.NormNum",
             "import Mathlib.Tactic.FinCases",
             "import ClaudeL1.Data.Assembly", "",
             "namespace ThomsonN9.Claude.L1", "open ThomsonN9.Claude.L1.KC ThomsonN9.Claude.L1.Data", "",
             "/-- coefficients of the reduced minorant (exact rationals, JSON field `minorant`, increasing powers) -/",
             f"def hNewCoeff : Fin 21 → ℚ := ![\n    {vec}]", "",
             "/-- the reduced minorant `h_new(t) = Σ_{i=0}^{20} hNewCoeff i * t^i` -/",
             "noncomputable def hNew (t : ℝ) : ℝ := ∑ i : Fin 21, (hNewCoeff i : ℝ) * t ^ (i : ℕ)", "",
             "/-- JSON field `raw_energy` (e_new) -/",
             f"def rawEnergyReduced : ℚ := {qlit(data['raw_energy'])}", "",
             "/-- JSON field `certified_energy` (= e_new - 36 L_new exactly) -/",
             f"def certifiedEnergyReduced : ℚ := {qlit(data['certified_energy'])}", "",
             "/-- integer numerators `10^60 * hNewCoeff i` -/",
             f"def hNumR : Fin 21 → ℤ := ![\n    {hv}]", "",
             "theorem hNum_length : hNum.length = 21 := rfl", "",
             "theorem hNum_getD (i : Fin 21) : hNum.getD i 0 = hNumR i := by",
             "  fin_cases i <;> rfl", "",
             "theorem hNewCoeff_eq (i : Fin 21) : (hNewCoeff i : ℝ) = (hNumR i : ℝ) / 10 ^ 60 := by",
             "  fin_cases i <;> simp [hNewCoeff, hNumR] <;> norm_num", "",
             "theorem c0_eq : (c0 : ℝ) = -(9 * 10 ^ 124) * (rawEnergyReduced : ℝ) / 36 := by",
             "  simp [c0, rawEnergyReduced]", "  norm_num", "",
             "theorem Lres_eq : (Lres : ℝ) / (9 * 10 ^ 124) =",
             "    ((rawEnergyReduced : ℝ) - (certifiedEnergyReduced : ℝ)) / 36 := by",
             "  simp [Lres, rawEnergyReduced, certifiedEnergyReduced]", "  norm_num", "",
             "end ThomsonN9.Claude.L1", ""]
    return write(HERE / "lean" / "ClaudeL1" / "Numbers.lean", "\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max-leaves", type=int, default=13000)
    args = ap.parse_args()
    data = M.load()
    # ---- exact model and self-check (same computation the Lean kernel re-does)
    kcols = M.kernel_cols(data)
    pk = M.kernel_total(kcols)
    blocks = M.sos_columns(data)
    H, c0, e = M.lhs_data(data)
    gen_mult()
    kstat = gen_kernel(kcols, pk)
    chunks, tot, sstats = gen_sos(blocks, args.max_leaves)
    n = len(chunks)
    # alias module for the last total (lets Assembly import it without knowing n)
    write(OUT / "SOS" / "Last.lean", "\n".join([
        HEADER, "import ClaudeL1.KC.Chain", f"import ClaudeL1.Data.SOS.T{n:02d}", "",
        f"namespace {NS}.SOS", "open ThomsonN9.Claude.L1.KC", "",
        f"/-- the final SOS running total (= T{n:02d}) -/",
        f"noncomputable def Tlast : PTree := T{n:02d}", "",
        f"theorem Tlast_eq : Tlast = T{n:02d} := rfl", "", f"end {NS}.SOS", ""]))
    R = M.residual(M.lhs_poly(H, c0), pk, tot)
    l1 = M.poly_l1(R)
    Ln = M.L_new(data)
    Lres = Ln * M.S_GLOB
    assert Lres.denominator == 1
    Lres = int(Lres)
    assert l1 == Lres, (l1, Lres)
    astat = gen_assembly(H, c0, pk, tot, Lres)
    gen_numbers(data, H)

    order = ["ClaudeL1.Data.Mult", "ClaudeL1.Data.Kernel", "ClaudeL1.Data.SOS.T00"]
    for i in range(1, n + 1):
        order += [f"ClaudeL1.Data.SOS.T{i:02d}", f"ClaudeL1.Data.SOS.C{i:02d}"]
    order += ["ClaudeL1.Data.SOS.Last", "ClaudeL1.Data.SOS.Glue", "ClaudeL1.Data.Assembly"]
    manifest = {
        "certificate": str(M.CERT), "sha256": M.SHA,
        "scales": {"delta": str(M.DELTA), "gscale": M.GSCALE, "S": str(M.S_GLOB), "hscale": str(M.HSCALE),
                   "kscale": M.KSCALE, "sscale": M.SSCALE},
        "raw_energy": str(e), "certified_energy": data["certified_energy"], "L_new": str(Ln),
        "Lres": str(Lres), "c0": str(c0), "hNum": [str(h) for h in H],
        "kernel": kstat, "sos_chunks": sstats, "assembly": astat,
        "sos_columns": sum(s["cols"] for s in sstats), "sos_leaves": sum(s["col_leaves"] for s in sstats),
        "build_order": order,
        "generated_sha256": dict(sorted(GENERATED.items())),
    }
    frozen = HERE / "data" / "generated_sha256.json"
    if frozen.exists():
        ref = json.loads(frozen.read_text())
        assert ref == manifest["generated_sha256"], "generated files differ from data/generated_sha256.json"
        print("generated files match data/generated_sha256.json")

    (HERE / "data").mkdir(exist_ok=True)
    (HERE / "data" / "manifest.json").write_text(json.dumps(manifest, indent=1))
    print(json.dumps({"chunks": n, "kernel_w": kstat["w"], "assembly_w": astat["w"],
                      "chunk_w": [s["w"] for s in sstats], "chunk_leaves": [s["col_leaves"] for s in sstats],
                      "residual_l1_equals_S_Lnew": True}, indent=None))


if __name__ == "__main__":
    main()
